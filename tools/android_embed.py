#!/usr/bin/env python3
"""Write a text file as a C string literal to include (the host's upscaler shaders).

The third-party shader files stay unchanged in port/third_party/; the host
(port/android/host/host_upscale.c) includes their text as

    static const char text[] =
    #include "name.inc"
    ;

Usage: android_embed.py input output
"""

import sys


def main():
    source, output = sys.argv[1], sys.argv[2]
    with open(source, encoding="utf-8") as f:
        text = f.read()
    lines = []
    for line in text.splitlines(keepends=True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")
        escaped = escaped.replace("\t", "\\t").replace("??", "?\\?")
        lines.append(f'"{escaped}"')
    with open(output, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/android_embed.py from " + source + "; do not edit */\n")
        f.write("\n".join(lines) if lines else '""')
        f.write("\n")


if __name__ == "__main__":
    main()
